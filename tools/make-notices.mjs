// Write src-tauri/licenses/THIRD-PARTY-NOTICES.txt: the copyright notices and licences of
// everything shipped inside Vellum, which the installer puts beside the exe and Help > About
// opens. Run by `tauri build` (beforeBuildCommand), so it always matches what's built.
//
//   node tools/make-notices.mjs
//
// - PDFium and the libraries built into pdfium.dll: src-tauri/licenses/pdfium/, committed
//   (tools/fetch-pdfium-licences.mjs refreshes it after a PDFium update).
// - Rust crates: those compiled into the app for this machine's target (`cargo metadata`,
//   normal dependencies only: build scripts and tests don't ship), with the licence files
//   from each crate's package. A text seen before is referred back to rather than repeated.
// - Front-end packages: what Vite bundles (package.json dependencies, plus Svelte's runtime
//   and Vite's own small runtime), with their licence files. The fonts' SIL Open Font
//   Licence comes with their @fontsource packages.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src-tauri/licenses/THIRD-PARTY-NOTICES.txt");
const LICENCE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

const norm = (t) => t.replace(/\r\n/g, "\n").replace(/\t/g, "    ").trimEnd();
const seen = new Map(); // text hash -> where it was first printed

/** A package's licence files as text, a text already printed elsewhere referred to. */
function licenceTexts(dir, who) {
  if (!existsSync(dir)) return [];
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort();
  return files.map((f) => {
    const text = norm(readFileSync(join(dir, f), "utf8"));
    const h = createHash("sha256").update(text).digest("hex");
    const first = seen.get(h);
    if (first) return `--- ${f}: the same text as ${first}, above.`;
    seen.set(h, `${who} (${f})`);
    return `--- ${f}\n\n${text}`;
  });
}

function section(title, body) {
  return `\n\n${"=".repeat(78)}\n${title}\n${"=".repeat(78)}\n${body}`;
}

// ---- Rust ----

function rustCrates() {
  const host = /host: (\S+)/.exec(execFileSync("rustc", ["-vV"], { encoding: "utf8" }))?.[1];
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", host], {
      cwd: join(root, "src-tauri"),
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
  // Normal (shipped) dependencies, from the app down.
  const keep = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (keep.has(id)) continue;
    keep.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
    }
  }
  keep.delete(meta.resolve.root);
  return [...keep].map((id) => pkgs.get(id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

// ---- Front end ----

function frontEndPackages() {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const found = new Map();
  const visit = (name, deep) => {
    if (found.has(name)) return;
    const dir = join(root, "node_modules", name);
    const file = join(dir, "package.json");
    if (!existsSync(file)) return;
    const p = JSON.parse(readFileSync(file, "utf8"));
    found.set(name, { name, version: p.version, license: p.license ?? "(not stated)", repository: p.repository?.url ?? p.repository ?? p.homepage ?? "", dir });
    if (deep) for (const d of Object.keys(p.dependencies ?? {})) visit(d, true);
  };
  for (const d of Object.keys(pkg.dependencies ?? {})) visit(d, true);
  visit("svelte", true); // its runtime is bundled
  visit("vite", false); // a small module-preload runtime
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
}

// ---- Write ----

const crates = rustCrates();
const fe = frontEndPackages();
const pdfium = readFileSync(join(root, "src-tauri/licenses/pdfium/PDFIUM-LICENCES.txt"), "utf8");

let text =
  `Vellum: third-party notices\n\n` +
  `Vellum is copyright (c) 2026 Matt James, under the MIT licence (LICENSE.txt beside this file).\n` +
  `It includes the third-party software below, each under its own licence. This file was\n` +
  `generated by tools/make-notices.mjs when this copy of Vellum was built.\n\n` +
  `Contents: PDFium and its libraries; ${crates.length} Rust crates; ${fe.length} front-end packages\n` +
  `(including the Inter and JetBrains Mono fonts, under the SIL Open Font License 1.1).`;

// The build itself comes from bblanchon/pdfium-binaries, whose licence ships with the download.
const binaries = join(root, "src-tauri/pdfium/LICENSE");
const binariesText = existsSync(binaries)
  ? `\n\n==== bblanchon/pdfium-binaries (the build scripts) ====\n\n${norm(readFileSync(binaries, "utf8"))}`
  : "";
text += section("PDFium and the libraries built into pdfium.dll", "\n" + norm(pdfium) + binariesText);

text += section(
  "Rust crates",
  crates
    .map((c) => {
      const who = `${c.name} ${c.version}`;
      const head = `\n\n---- ${who}\nLicence: ${c.license ?? "(not stated)"}${c.repository ? `\nSource: ${c.repository}` : ""}`;
      const texts = licenceTexts(dirname(c.manifest_path), who);
      return head + (texts.length ? "\n\n" + texts.join("\n\n") : "\n(No licence file in the package; the licence named above applies.)");
    })
    .join(""),
);

text += section(
  "Front-end packages",
  fe
    .map((p) => {
      const who = `${p.name} ${p.version}`;
      const head = `\n\n---- ${who}\nLicence: ${p.license}${p.repository ? `\nSource: ${String(p.repository).replace(/^git\+/, "")}` : ""}`;
      const texts = licenceTexts(p.dir, who);
      return head + (texts.length ? "\n\n" + texts.join("\n\n") : "\n(No licence file in the package; the licence named above applies.)");
    })
    .join(""),
);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text.replace(/\n/g, "\r\n") + "\r\n");
console.log(`[notices] ${crates.length} crates, ${fe.length} front-end packages: ${Math.round(text.length / 1024)} KB -> src-tauri/licenses/THIRD-PARTY-NOTICES.txt`);
